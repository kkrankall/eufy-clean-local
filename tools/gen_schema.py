"""Regenerate custom_components/eufy_clean_local/schema.py from tools/protos.

Needs grpcio-tools: python -m pip install grpcio-tools
"""
import base64
import pathlib
import subprocess
import sys
import tempfile
import textwrap
import zlib

root = pathlib.Path(__file__).resolve().parent
protos = sorted((root / "protos" / "proto" / "cloud").glob("*.proto"))
with tempfile.TemporaryDirectory() as tmp:
    out = pathlib.Path(tmp) / "schema.pb"
    subprocess.run([sys.executable, "-m", "grpc_tools.protoc", f"-I{root / 'protos'}",
                    "--include_imports", f"--descriptor_set_out={out}", *map(str, protos)], check=True)
    blob = base64.b64encode(zlib.compress(out.read_bytes(), 9)).decode()
target = root.parent / "custom_components" / "eufy_clean_local" / "schema.py"
target.write_text(
    '"""Protobuf schema for eufy robot vacuums, recovered from the eufy app.\n\n'
    "Generated by tools/gen_schema.py from tools/protos (zlib + base64); do not edit.\n"
    '"""\n\nDESCRIPTOR_SET = (\n'
    + "".join(f'    "{line}"\n' for line in textwrap.wrap(blob, 96))
    + ")\n"
)
print(f"wrote {target} ({len(blob)} base64 chars, {len(protos)} files)")
